TICKET = {"n": 7320}


def new_order():
    """12 位订单号：20 + 年份2位 + 4位 + 4位，例 202610150001。"""
    return "20{:02d}{:04d}{:04d}".format(RNG.randint(25, 26), RNG.randint(1, 1231), RNG.randint(1, 9999))


def new_express():
    """12 位运单号，例 7836 2144 4471。"""
    return "78" + "".join(str(RNG.randint(0, 9)) for _ in range(10))


def new_phone():
    return "1{}{}".format(RNG.choice("3578"), "".join(str(RNG.randint(0, 9)) for _ in range(9)))


def new_ticket():
    TICKET["n"] += RNG.randint(1, 7)
    return "TK{}{:05d}".format(RNG.randint(25, 26), TICKET["n"])


def new_addr():
    """返回完整原始地址，并登记到 EXACT_MASK 供精确脱敏。"""
    prov, city = RNG.choice(CITIES)
    raw = "{}{}{}区{}路{}号{}室".format(
        prov, city, RNG.choice(["余杭", "滨江", "西湖", "朝阳", "海淀", "浦东", "天河"]),
        RNG.choice(["文一", "春晓", "解放", "中山", "人民"]), RNG.randint(1, 200),
        RNG.randint(101, 2508))
    register_mask(raw, "{}{}****".format(prov, city))
    return raw


def rand_time():
    """近 12 个月内的咨询时间，大促月份加权。"""
    start = dt.datetime(2025, 10, 16)
    end = dt.datetime(2026, 10, 15)
    hot = [(dt.datetime(2025, 11, 1), dt.datetime(2025, 11, 15)),
           (dt.datetime(2025, 12, 8), dt.datetime(2025, 12, 15)),
           (dt.datetime(2026, 6, 1), dt.datetime(2026, 6, 20)),
           (dt.datetime(2026, 1, 10), dt.datetime(2026, 1, 28))]
    if RNG.random() < 0.42:
        a, b = RNG.choice(hot)
        t = a + dt.timedelta(seconds=RNG.randint(0, int((b - a).total_seconds())))
    else:
        t = start + dt.timedelta(seconds=RNG.randint(0, int((end - start).total_seconds())))
    return t.replace(hour=RNG.randint(9, 22), minute=RNG.randint(0, 59), second=RNG.randint(0, 59))


def make_entities(*texts):
    """按需生成一份实体（问句与答句共用，保证同一会话里的订单号/运单号一致）。"""
    joined = " ".join(texts)
    bag = {}
    if "{order}" in joined or "{order_m}" in joined:
        bag["order"] = new_order()
    if "{express}" in joined or "{express_m}" in joined:
        bag["express"] = new_express()
    if "{addr_m}" in joined:
        bag["addr_m"] = new_addr()
    if "{name_m}" in joined:
        bag["name_m"] = RNG.choice(SURNAMES) + RNG.choice(GIVEN) + RNG.choice(["先生", "女士", "小姐"])
    if "{phone_m}" in joined:
        bag["phone_m"] = new_phone()
    if "{ticket}" in joined:
        bag["ticket"] = new_ticket()
    if "{sess}" in joined:
        bag["sess"] = "sess_" + "%08x" % RNG.getrandbits(32)
    return bag


def apply_entities(text, bag):
    """把占位符替换成原始（未脱敏）实体。"""
    for key, val in bag.items():
        text = text.replace("{" + key + "}", val)
    if "order" in bag:
        text = text.replace("{order_m}", bag["order"])
    if "express" in bag:
        text = text.replace("{express_m}", bag["express"])
    return text


def build_records():
    by_cat = {}
    for sc in SCENARIOS:
        by_cat.setdefault(sc[0], []).append(sc)

    records = []
    for cat in INTENT_ORDER:
        pool = by_cat[cat]
        need = INTENT_COUNT[cat]
        made = 0
        while made < need:
            for sc in pool:
                if made >= need:
                    break
                _, sub, sku_pool, qa_list, p_trans, emo_w = sc
                sku = RNG.choice(sku_pool)
                q_tpl, a_tpl = RNG.choice(qa_list)   # 问答成对取样
                bag = make_entities(q_tpl, a_tpl)
                q = apply_entities(sku_fill(q_tpl, sku), bag)
                a = apply_entities(sku_fill(a_tpl, sku), bag)

                # 少量记录用户会主动留手机号 / 微信 / 收货人（用于验证脱敏规则命中）。
                # 只在售后、订单、兜底这类「需要联系买家」的场景注入，避免出现
                # 「怎么买最划算，我的电话是…」这种不合语境的句子。
                if cat in ("售后服务", "订单服务", "兜底"):
                    if RNG.random() < 0.14:
                        q = q + "，我的电话是 {}，麻烦联系我".format(new_phone())
                    if RNG.random() < 0.07:
                        q = q + "，可以加我微信 kefu_demo{}".format(RNG.randint(100, 999))
                    if RNG.random() < 0.08:
                        nm = RNG.choice(SURNAMES) + RNG.choice(GIVEN)
                        q = q + "，收货人{}".format(nm + RNG.choice(["先生", "女士"]))

                transfer = RNG.random() < p_trans
                if sub == "显式转人工":
                    transfer = True
                if sub == "闲聊":
                    transfer = False   # 闲聊类不触发转人工

                emo = RNG.choices(EMOTIONS, weights=emo_w, k=1)[0]
                if cat == "兜底" and sub == "闲聊" and emo in ("不满", "愤怒"):
                    emo = RNG.choice(["中性", "满意"])
                if transfer and emo == "满意":
                    emo = "中性"

                records.append({
                    "渠道": RNG.choices(CHANNELS, weights=CHANNEL_W, k=1)[0],
                    "时间": rand_time(),
                    "用户问题": q,
                    "客服回复": a,
                    "意图类目": cat,
                    "_子意图": sub,
                    "是否转人工": "是" if transfer else "否",
                    "用户情绪": emo,
                })
                made += 1

    records.sort(key=lambda r: r["时间"])
    for i, r in enumerate(records, start=1):
        r["会话ID"] = "CS{}-{:04d}".format(r["时间"].strftime("%Y%m%d"), i)
    return records


